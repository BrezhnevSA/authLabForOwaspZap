
var HttpMessage = Java.type("org.parosproxy.paros.network.HttpMessage");
var HttpRequestHeader = Java.type("org.parosproxy.paros.network.HttpRequestHeader");
var HttpHeader = Java.type("org.parosproxy.paros.network.HttpHeader");
var URI = Java.type("org.apache.commons.httpclient.URI");
var ScriptVars = Java.type("org.zaproxy.zap.extension.script.ScriptVars");
var ReentrantLock = Java.type("java.util.concurrent.locks.ReentrantLock");
var URLEncoder = Java.type("java.net.URLEncoder");
var LogManager = Java.type("org.apache.logging.log4j.LogManager");
var LOGGER = LogManager.getLogger("1c-http-sender-auth");

LOGGER.info("[1c-http-sender-auth] SCRIPT INITIALIZED");
/*
 * 1C authentication through HTTP Sender script
 *
 * Flow:
 * 1) POST /app/e1cib/start
 * Content-Type: application/x-www-form-urlencoded
 * usr=<username>
 * pwd=<password>
 * authfailhandling=error
 *
 * 2) Server returns:
 * HTTP 301
 * vrs-session2: <UUID>
 * Location: /app/?VRSSESSION2=<UUID>&OIDA-
 *
 * 3) Open Location.
 *
 * 4) POST /app/ru/e1cib/login
 *     ?version=8.3.23.2040
 *     &sid=<UUID>
 *     &nooida
 *     &vl=ru
 *     &clnId=<client-id>
 * Body is EMPTY.
 *
 * 5) Successful response contains:
 *
 * {
 *   "response": {
 *     "seance": "<UUID>",
 *     ...
 *   }
 * }
 *
 * 6) All subsequent ZAP requests receive:
 * vrs-session: <UUID>
 *
 * IMPORTANT:
 *
 * /e1cib/login also returns a long encoded response header:
 * vrs-session: ZDI3Zm...
 * We DO NOT use it.
 * The real browser traffic sends the plain UUID from sid/seance.
 */

/*
 * CONFIGURATION
 */

/*
 * URL of 1C as seen from ZAP.
 */
var MANAGED_HOST = "mock-1c";
var ORIGIN = "http://" + MANAGED_HOST + ":8704";
/*
 * Published 1C application.
 */
var APP_PATH = "/app";

/*
 * Locale selected by the application.
 *
 * From your HAR:
 *
 * /app/ru/e1cib/login
 */
var LOCALE_PATH = "ru_RU";

var VL = "ru";

/*
 * 1C platform version seen in HAR.
 */
var VERSION = "8.3.25.1445";

/*
 * Client id
 */
var UUID = Java.type("java.util.UUID");
var CLIENT_ID = String(UUID.randomUUID());

/*
 * Credentials.
 */
var USERNAME = "zapuser";
var PASSWORD = "ZapTest123!";

/*
 * INTERNAL CONFIGURATION
 */
var API_URL = ORIGIN + APP_PATH;
var START_URL = API_URL + "/e1cib/start";
var LOGIN_URL = API_URL + "/" + LOCALE_PATH + "/e1cib/login";
var SESSION_HEADER = "vrs-session";
var SESSION2_HEADER = "vrs-session2";

/*
 * This header is only used internally so requests generated by this script
 * don't recursively trigger authentication again.
 */
var INTERNAL_AUTH_HEADER = "X-ZAP-Internal-1C-Auth";
var SCRIPT_CONTEXT = this.context;
var SCRIPT_NAME = this["zap.script.name"] || "1c-http-sender-auth";
var SESSION_KEY = "1c-vrs-session";

/*
 * ZAP scanner can send many requests simultaneously.
 *
 * Without this lock several threads could perform /e1cib/start at the
 * same time and create several different 1C sessions.
 */
var authenticationLock = new ReentrantLock();

/*
 * COMMON HELPERS
 */
/*LOGGER.info("SCRIPT LOADED. API_URL=" + API_URL);*/
function log(message) {
    LOGGER.info("[" + SCRIPT_NAME + "] " + message);
}

function getRequestUrl(msg) {
    return String(
        msg.getRequestHeader()
            .getURI()
            .toString()
    );
}

function isManagedRequest(msg) {
    var uri = msg.getRequestHeader().getURI();
    var host = String(uri.getHost());
    return host.toLowerCase() === MANAGED_HOST.toLowerCase();
}

function isInternalAuthRequest(msg) {
    return msg.getRequestHeader().getHeader(INTERNAL_AUTH_HEADER) === "1";
}

function markAsInternal(message) {
    message.getRequestHeader().setHeader(INTERNAL_AUTH_HEADER, "1");
}

function getCachedSession() {
    var value = ScriptVars.getScriptVar(SCRIPT_CONTEXT, SESSION_KEY);
    if (value === null || value === undefined || String(value).length === 0) {
        return null;
    }
    return String(value);
}

function saveSession(sessionId) {
    ScriptVars.setScriptVar(SCRIPT_CONTEXT, SESSION_KEY, String(sessionId));
}

function clearSession() {
    /*
     * Empty string is used instead of null to avoid problems between
     * Java/GraalJS versions.
     */
    ScriptVars.setScriptVar(SCRIPT_CONTEXT, SESSION_KEY, "");
}

function encode(value) {
    return String(URLEncoder.encode(String(value), "UTF-8"));
}

function isSuccessfulStatus(status) {
    return status >= 200 && status < 400;
}

/*
 * Convert Location response header to absolute URL.
 */
function makeAbsoluteUrl(location) {
    if (location === null || location === undefined || String(location).length === 0) {
        return null;
    }
    location = String(location);
    if (location.indexOf("https://") === 0 || location.indexOf("http://") === 0) {
        return location;
    }
    if (location.charAt(0) === "/") {
        return ORIGIN + location;
    }
    return API_URL + "/" + location;
}

/*
 * STEP 1 POST /app/e1cib/start
 */
function createStartRequest() {
    var uri = new URI(START_URL, false);
    var requestHeader = new HttpRequestHeader(HttpRequestHeader.POST, uri, HttpHeader.HTTP11);
    requestHeader.setHeader("Content-Type", "application/x-www-form-urlencoded; charset=UTF-8");
    requestHeader.setHeader("Accept", "text/html,application/xhtml+xml,*/*");
    var message = new HttpMessage(requestHeader);
    message.setRequestBody(
        "usr=" + encode(USERNAME)
        + "&pwd=" + encode(PASSWORD)
        + "&authfailhandling=error"
    );
    message.getRequestHeader()
        .setHeader("Content-Length", String(message.getRequestBody().length()));
    markAsInternal(message);
    return message;
}

/*
 * STEP 2 GET /app/?VRSSESSION2=<uuid>&OIDA-
 */
function createLandingRequest(url) {
    var uri = new URI(url, false);
    var requestHeader = new HttpRequestHeader(HttpRequestHeader.GET, uri, HttpHeader.HTTP11);
    requestHeader.setHeader("Accept", "text/html,application/xhtml+xml,*/*");
    var message = new HttpMessage(requestHeader);
    markAsInternal(message);
    return message;
}

/*
 * STEP 3 POST /app/ru/e1cib/login
 */
function createLoginRequest(sessionId) {
    var url = LOGIN_URL
        + "?version=" + encode(VERSION)
        + "&sid=" + encode(sessionId)
        + "&nooida"
        + "&vl=" + encode(VL)
        + "&clnId=" + encode(CLIENT_ID);
    var uri = new URI(url, false);
    var requestHeader = new HttpRequestHeader(HttpRequestHeader.POST, uri, HttpHeader.HTTP11);
    requestHeader.setHeader("Accept", "application/json");
    requestHeader.setHeader("Content-Type", "application/json; charset=UTF-8");
    requestHeader.setHeader("Origin", ORIGIN);
    requestHeader.setHeader("Referer", API_URL + "/" + LOCALE_PATH + "/");
    var message = new HttpMessage(requestHeader);
    message.setRequestBody("");
    message.getRequestHeader().setHeader("Content-Length", "0");
    markAsInternal(message);
    return message;
}

/*
 * AUTHENTICATION
 */
function authenticate(helper) {
    authenticationLock.lock();
    try {
        /*
         * Another worker might have authenticated while this worker waited for the lock.
         */
        var existingSession = getCachedSession();
        if (existingSession !== null) {
            return existingSession;
        }
        /*
         * STEP 1: usr/password -> VRSSESSION2
         */
        var startMessage = createStartRequest();
        LOGGER.info("POST " + START_URL);
        /*LOGGER.info("/e1cib/start REQUEST HEADERS:\n"
            + String(startMessage.getRequestHeader()));
        LOGGER.info("/e1cib/start REQUEST BODY:\n"
            + String(startMessage.getRequestBody()));*/
        helper.getHttpSender().sendAndReceive(startMessage, false);
        var startStatus = startMessage.getResponseHeader().getStatusCode();
        LOGGER.info("/e1cib/start HTTP " + startStatus);
        /*LOGGER.info("/e1cib/start RESPONSE HEADERS:\n"
            + String(startMessage.getResponseHeader()));
        LOGGER.info("/e1cib/start RESPONSE BODY:\n"
            + String(startMessage.getResponseBody()));*/
        if (!isSuccessfulStatus(startStatus)) {
            throw "1C /e1cib/start returned HTTP " + startStatus;
        }
        /*
         * Successful response from server:
         * vrs-session2: d27ffdb7-f447-4684-aa54-e079e20985f7
         */
        var sessionId = startMessage.getResponseHeader().getHeader(SESSION2_HEADER);
        if (sessionId === null || sessionId === undefined || String(sessionId).length === 0) {
            throw "1C /e1cib/start did not return " + SESSION2_HEADER;
        }
        sessionId = String(sessionId);
        LOGGER.info("Received " + SESSION2_HEADER + "=" + sessionId);
        /*
         * STEP 2: Open Location returned by /e1cib/start.
         */
        var location = startMessage.getResponseHeader().getHeader("Location");
        var landingUrl = makeAbsoluteUrl(location);
        /*
         * Fallback in case Location is missing for some 1C configuration.
         */
        if (landingUrl === null) {
            landingUrl = API_URL + "/?VRSSESSION2=" + encode(sessionId) + "&OIDA-";
        }
        LOGGER.info("Opening landing URL: " + landingUrl);
        var landingMessage = createLandingRequest(landingUrl);
        /*
         * Follow redirect: /app/?VRSSESSION2=... -> /app/ru/
         */
        helper.getHttpSender().sendAndReceive(landingMessage, true);
        var landingStatus = landingMessage.getResponseHeader().getStatusCode();
        LOGGER.info("Landing HTTP " + landingStatus);
        if (!isSuccessfulStatus(landingStatus)) {
            throw "1C landing URL returned HTTP " + landingStatus;
        }
        /*
         * STEP 3: Activate authenticated web-client session.
         */
        var loginMessage = createLoginRequest(sessionId);
        LOGGER.info("POST " + LOGIN_URL + " sid=" + sessionId);
        helper.getHttpSender().sendAndReceive(loginMessage, false);
        var loginStatus = loginMessage.getResponseHeader().getStatusCode();
        LOGGER.info("/e1cib/login HTTP " + loginStatus);
        if (loginStatus < 200 || loginStatus >= 300) {
            throw "1C /e1cib/login returned HTTP " + loginStatus;
        }
        /*
         * Verify that this is really the authenticated session.
         */
        var responseText = String(loginMessage.getResponseBody());
        var expectedSeance = '"seance":"' + sessionId + '"';
        if (responseText.indexOf(expectedSeance) === -1) {
            throw "1C login response does not contain expected seance=" + sessionId;
        }
        /*
         * Intentionally store the PLAIN UUID. Do not take the long encoded vrs-session response header.
         */
        saveSession(sessionId);
        LOGGER.info("Authentication successful. " + SESSION_HEADER + "=" + sessionId);
        return sessionId;
    } catch (error) {
        clearSession();
        LOGGER.info("AUTHENTICATION FAILED: " + error);
        return null;
    } finally {
        authenticationLock.unlock();
    }
}

/*
 * HTTP SENDER CALLBACK
 */
function sendingRequest(msg, initiator, helper) {
    /*LOGGER.info("sendingRequest URL=" + getRequestUrl(msg));*/
    /*
     * Do not process requests generated by authenticate() itself.
     */
    if (isInternalAuthRequest(msg)) {
        /*LOGGER.info("skip: internal auth request");*/
        return;
    }
    /*
     * Do not put 1C session header on unrelated domains.
     */
    if (!isManagedRequest(msg)) {
        /*LOGGER.info("skip: URL does not match API_URL=" + API_URL);*/
        return;
    }
    var sessionId = getCachedSession();
    /*
     * No session yet -> authenticate.
     */
    if (sessionId === null) {LOGGER.info("No session available. Sending request without " + SESSION_HEADER + ": " + getRequestUrl(msg));
        sessionId = authenticate(helper);
    }
    if (sessionId === null) {
        /*LOGGER.info(
            "No session available. Sending request without "
            + SESSION_HEADER
            + ": "
            + getRequestUrl(msg)
        );*/
        return;
    }
    /*LOGGER.info("Set " + SESSION_HEADER + "=" + sessionId + " for " + getRequestUrl(msg));*/
    /*
     * Every Spider / AJAX Spider / Active Scan request gets vrs-session: <plain UUID>
     */
    msg.getRequestHeader().setHeader(SESSION_HEADER, sessionId);
}

/*
 * RESPONSE CALLBACK
 */
function responseReceived(msg, initiator, helper) {
    if (isInternalAuthRequest(msg)) {
        return;
    }
    if (!isManagedRequest(msg)) {
        return;
    }
    var status = msg.getResponseHeader().getStatusCode();
    /*
     * Basic automatic reauthentication.
     * If 1C/proxy reports that the session is no longer authorized,
     * clear it. The next outgoing request will call authenticate().
     */
    if (status === 401 || status === 403) {
        LOGGER.info("HTTP " + status + " received. Clearing cached 1C session.");
        clearSession();
    }
}
